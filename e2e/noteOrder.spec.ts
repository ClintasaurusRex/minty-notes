import { expect, test, type Page } from '@playwright/test'
import { waitSaved } from './helpers'

async function projectWithNotes(page: Page) {
  await page.goto('/')
  await page.getByTestId('rail-projects').click()
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name').fill('Note ordering')
  for (const title of ['A', 'B', 'C']) {
    await page.getByRole('button', { name: 'New project note', exact: true }).click()
    await page.getByLabel('Page title').fill(title)
    await waitSaved(page)
  }
}

const titles = (page: Page) => page.locator('.project-note-list .nav-page-title')

test('note ordering by keyboard and buttons persists with mode after reload', async ({ page }) => {
  await projectWithNotes(page)
  await expect(page.getByLabel('Sort project notes')).toHaveValue('last-edited')
  await expect(titles(page)).toHaveText(['C', 'B', 'A'])
  const a = page.locator('.project-note-list .nav-page').filter({ has: page.getByText('A', { exact: true }) })
  await a.focus()
  await page.keyboard.press('Alt+ArrowUp')
  await expect(titles(page)).toHaveText(['C', 'A', 'B'])
  await expect(page.getByLabel('Sort project notes')).toHaveValue('manual')
  await expect(a).toBeFocused()
  await expect(page.getByRole('status').filter({ hasText: 'Moved “A” to position 2 of 3' })).toBeVisible()
  await page.getByRole('button', { name: 'Move C down', exact: true }).click()
  await expect(titles(page)).toHaveText(['A', 'C', 'B'])
  await waitSaved(page)
  await page.reload()
  await expect(page.getByLabel('Sort project notes')).toHaveValue('manual')
  await expect(titles(page)).toHaveText(['A', 'C', 'B'])
  await page.locator('.project-note-list .nav-page').filter({ has: page.getByText('B', { exact: true }) }).click()
  await page.getByLabel('Page title').fill('B edited')
  await waitSaved(page)
  await expect(titles(page)).toHaveText(['A', 'C', 'B edited'])
  await page.getByLabel('Sort project notes').selectOption('last-edited')
  await expect(titles(page)).toHaveText(['B edited', 'C', 'A'])
})

test('dragging a grip shows destination, selects Manual, and keeps note editing separate', async ({ page }, testInfo) => {
  await projectWithNotes(page)
  const handle = page.getByRole('button', { name: /^Reorder A, position 3 of 3$/ })
  const target = page.locator('.project-note-row').filter({ has: page.getByText('C', { exact: true }) })
  const from = (await handle.boundingBox())!
  const to = (await target.boundingBox())!
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(from.x + from.width / 2 + 8, from.y + from.height / 2, { steps: 3 })
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 8 })
  await page.mouse.move(to.x + to.width / 2 + 1, to.y + to.height / 2)
  await expect(target).toHaveClass(/note-drop-before/)
  await page.screenshot({ path: testInfo.outputPath('drop-destination.png') })
  await page.mouse.up()
  await expect(titles(page)).toHaveText(['A', 'C', 'B'])
  await expect(page.getByLabel('Sort project notes')).toHaveValue('manual')
  await waitSaved(page)
  await page.reload()
  await expect(titles(page)).toHaveText(['A', 'C', 'B'])
  await page.locator('.project-note-list .nav-page').filter({ has: page.getByText('A', { exact: true }) }).click()
  await expect(page.getByLabel('Page title')).toHaveValue('A')
})

test('read-only application window can navigate notes but cannot change sort or order', async ({ page, context }) => {
  await projectWithNotes(page)
  await page.getByLabel('Sort project notes').selectOption('manual')
  await waitSaved(page)
  const readonly = await context.newPage()
  await readonly.goto('/')
  await expect(readonly.getByTestId('readonly-banner')).toBeVisible()
  await expect(readonly.getByLabel('Sort project notes')).toBeDisabled()
  await expect(readonly.locator('.note-drag-handle')).toHaveCount(0)
  await expect(readonly.locator('.note-order-actions')).toHaveCount(0)
  await readonly.locator('.project-note-list .nav-page').filter({ has: readonly.getByText('A', { exact: true }) }).click()
  await expect(readonly.getByLabel('Page title')).toHaveValue('A')
  await readonly.close()
})

test('dropping on the end target appends the note and persists the exact sequence', async ({ page }) => {
  await projectWithNotes(page)
  const grip = page.getByRole('button', { name: /^Reorder C, position 1 of 3$/ })
  const from = (await grip.boundingBox())!
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(from.x + from.width / 2 + 12, from.y + from.height / 2, { steps: 4 })
  const end = page.getByText('Drop at end', { exact: true })
  await expect(end).toBeVisible()
  const to = (await end.boundingBox())!
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 10 })
  await page.mouse.move(to.x + to.width / 2 + 1, to.y + to.height / 2)
  await expect(end).toHaveClass(/note-drop-before/)
  await page.mouse.up()
  await expect(titles(page)).toHaveText(['B', 'A', 'C'])
  await expect(page.getByLabel('Sort project notes')).toHaveValue('manual')
  await expect(page.getByRole('status').filter({ hasText: 'Moved “C” to position 3 of 3' })).toBeAttached()
  // Mouse drops return focus to the note button; grip-arrow moves keep it on the grip.
  await expect(page.locator('.project-note-list .nav-page').filter({ has: page.getByText('C', { exact: true }) })).toBeFocused()
  await waitSaved(page)
  await page.reload()
  await expect(titles(page)).toHaveText(['B', 'A', 'C'])
})

test('phone-sized touch navigation keeps note moves and opening a note reachable', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 900 }, hasTouch: true })
  const page = await context.newPage()
  try {
    await projectWithNotes(page)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.reload()
    await page.getByRole('button', { name: 'Show page list', exact: true }).click()
    await page.getByLabel('Sort project notes').selectOption('manual')
    await expect(titles(page)).toHaveText(['C', 'B', 'A'])
    const move = page.getByRole('button', { name: 'Move A up', exact: true })
    await expect(move).toBeInViewport()
    const target = (await move.boundingBox())!
    expect(target.width).toBeGreaterThanOrEqual(36)
    expect(target.height).toBeGreaterThanOrEqual(36)
    await move.click()
    await expect(titles(page)).toHaveText(['C', 'A', 'B'])
    await page.locator('.project-note-list .nav-page').filter({ has: page.getByText('B', { exact: true }) }).click()
    await expect(page.getByLabel('Page title')).toHaveValue('B')
    await expect(page.getByRole('button', { name: 'Show page list', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  } finally { await context.close() }
})

const noteButton = (page: Page, title: string) => page.locator('.project-note-list .nav-page').filter({ has: page.getByText(title, { exact: true }) })

async function editTitle(page: Page, from: string, to: string) {
  await noteButton(page, from).click()
  await page.getByLabel('Page title').fill(to)
  await waitSaved(page)
}

test('first Manual keeps the visible Last edited order; later switches keep the established Manual order (timestamps untouched)', async ({ page }) => {
  await projectWithNotes(page)
  await editTitle(page, 'A', 'A1') // Last edited: A1, C, B; creation order A, B, C
  await expect(titles(page)).toHaveText(['A1', 'C', 'B'])
  const metas = () => page.locator('.project-note-list .nav-page-meta').allTextContents()
  const shown = await metas()
  const sort = page.getByLabel('Sort project notes')
  await sort.selectOption('manual')
  await expect(titles(page)).toHaveText(['A1', 'C', 'B'])
  expect(await metas()).toEqual(shown)
  await page.getByRole('button', { name: 'Move B up', exact: true }).click()
  await expect(titles(page)).toHaveText(['A1', 'B', 'C'])
  await sort.selectOption('last-edited')
  await editTitle(page, 'C', 'C1')
  await expect(titles(page)).toHaveText(['C1', 'A1', 'B'])
  await sort.selectOption('manual')
  await expect(titles(page)).toHaveText(['A1', 'B', 'C1'])
  await sort.selectOption('last-edited')
  await waitSaved(page)
  await page.reload()
  await expect(sort).toHaveValue('last-edited')
  await expect(titles(page)).toHaveText(['C1', 'A1', 'B'])
  await sort.selectOption('manual')
  await expect(titles(page)).toHaveText(['A1', 'B', 'C1'])
})

test('reorder grips move with arrow keys, keep focus, and describe themselves', async ({ page }) => {
  await projectWithNotes(page)
  const grip = page.getByRole('button', { name: /^Reorder A, position 3 of 3$/ })
  await expect(grip).toHaveAttribute('aria-describedby', 'note-order-help')
  await expect(page.locator('#note-order-help')).toContainText('focus a grip and press ↑/↓')
  await grip.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status').filter({ hasText: 'Press the up or down arrow key to move it' })).toBeAttached()
  await page.keyboard.press('ArrowUp')
  await expect(titles(page)).toHaveText(['C', 'A', 'B'])
  await expect(page.getByLabel('Sort project notes')).toHaveValue('manual')
  const moved = page.getByRole('button', { name: /^Reorder A, position 2 of 3$/ })
  await expect(moved).toBeFocused()
  await expect(page.getByRole('status').filter({ hasText: 'Moved “A” to position 2 of 3' })).toBeAttached()
  await page.keyboard.press('ArrowUp')
  await expect(titles(page)).toHaveText(['A', 'C', 'B'])
  await expect(page.getByRole('button', { name: /^Reorder A, position 1 of 3$/ })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(titles(page)).toHaveText(['C', 'A', 'B'])
  await waitSaved(page)
  await page.reload()
  await expect(titles(page)).toHaveText(['C', 'A', 'B'])
})

test('a note moved into a Manual project appends last; a trashed note restores to its place; both survive reload', async ({ page }) => {
  await projectWithNotes(page)
  const sort = page.getByLabel('Sort project notes')
  await sort.selectOption('manual')
  await page.getByRole('button', { name: 'Move A up', exact: true }).click()
  await expect(titles(page)).toHaveText(['C', 'A', 'B'])
  // A note written elsewhere (the Inbox) and moved in through the page header.
  await page.keyboard.press('Alt+N')
  await page.getByLabel('Page title').fill('From inbox')
  await waitSaved(page)
  await page.getByRole('combobox', { name: 'Move page to' }).selectOption({ label: 'Note ordering' })
  await waitSaved(page)
  const openOrdering = async () => {
    await page.getByTestId('rail-projects').click()
    const back = page.getByRole('button', { name: /All projects/ })
    if (await back.isVisible()) await back.click()
    await page.locator('.navigator').getByRole('button', { name: /Note ordering/ }).click()
    await expect(page.getByLabel('Project name')).toHaveValue('Note ordering')
  }
  await openOrdering()
  await expect(sort).toHaveValue('manual')
  await expect(titles(page)).toHaveText(['C', 'A', 'B', 'From inbox'])
  // Trash the middle note, then restore it from the Trash list.
  await noteButton(page, 'A').click()
  await page.locator('.page-header').getByRole('button', { name: 'Trash', exact: true }).click()
  await expect(titles(page)).toHaveText(['C', 'B', 'From inbox'])
  await page.getByTestId('rail-trash').click()
  await page.locator('.trash-item').filter({ has: page.locator('.nav-page-title', { hasText: /^A$/ }) }).getByRole('button', { name: 'Restore' }).click()
  await waitSaved(page)
  await openOrdering()
  await expect(titles(page)).toHaveText(['C', 'A', 'B', 'From inbox'])
  await page.reload()
  await openOrdering()
  await expect(sort).toHaveValue('manual')
  await expect(titles(page)).toHaveText(['C', 'A', 'B', 'From inbox'])
})
