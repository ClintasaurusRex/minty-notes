import { expect, test } from '@playwright/test'
import { addTextBox, dragBy, newQuickNote, waitSaved } from './helpers'

test('navigation resizes by pointer and keyboard, remembers collapse and width, including read-only windows', async ({ page, context }) => {
  await page.goto('/')
  await page.getByTestId('rail-projects').click()
  const divider = page.getByRole('separator', { name: 'Resize navigation panel' })
  await expect(divider).toHaveAttribute('aria-valuenow', '264')
  await divider.press('Escape')
  await expect(divider).toBeVisible()
  await dragBy(page, divider, 90, 0)
  await expect(divider).toHaveAttribute('aria-valuenow', '354')
  await divider.press('ArrowRight')
  await expect(divider).toHaveAttribute('aria-valuenow', '364')
  await divider.press('End')
  await expect(divider).toHaveAttribute('aria-valuenow', '480')
  await divider.press('Home')
  await expect(divider).toHaveAttribute('aria-valuenow', '220')
  await divider.press('Shift+ArrowRight')
  await page.reload()
  await expect(divider).toHaveAttribute('aria-valuenow', '260')
  await divider.press('Enter')
  await expect(divider).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Show page list' })).toBeFocused()
  await page.reload()
  await expect(divider).toHaveCount(0)
  await page.getByRole('button', { name: 'Show page list' }).click()
  await expect(divider).toHaveAttribute('aria-valuenow', '260')
  const other = await context.newPage()
  await other.goto('/')
  await expect(other.getByTestId('readonly-banner')).toBeVisible()
  const readDivider = other.getByRole('separator', { name: 'Resize navigation panel' })
  await readDivider.press('ArrowRight')
  await expect(readDivider).toHaveAttribute('aria-valuenow', '270')
  await other.getByRole('button', { name: 'Collapse navigation panel' }).click()
  await expect(readDivider).toHaveCount(0)
})

test('closing or toggling the phone overlay does not overwrite the desktop collapse preference', async ({ page }) => {
  const pref = () => page.evaluate(() => localStorage.getItem('minty:navigation-collapsed'))
  await page.goto('/')
  await page.getByTestId('rail-projects').click()
  await expect(page.locator('#navigation-panel')).toBeVisible()
  // Desktop: expanded, remembered.
  await page.getByRole('button', { name: 'Hide page list' }).click()
  await page.getByRole('button', { name: 'Show page list' }).click()
  expect(await pref()).toBe('false')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.getByRole('button', { name: 'Show page list' }).click()
  await page.getByRole('button', { name: 'Collapse navigation panel' }).click()
  await page.getByRole('button', { name: 'Show page list' }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Show page list' }).click()
  await expect(page.locator('#navigation-panel')).toBeVisible()
  await page.keyboard.press('Alt+Backslash')
  await expect(page.locator('#navigation-panel')).toHaveCount(0)
  expect(await pref()).toBe('false')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.reload()
  await expect(page.locator('#navigation-panel')).toBeVisible()
  // A desktop collapse is still remembered.
  await page.getByRole('button', { name: 'Collapse navigation panel' }).click()
  expect(await pref()).toBe('true')
  await page.reload()
  await expect(page.locator('#navigation-panel')).toHaveCount(0)
})

test('phone navigation, shortcut help, quick capture and wide-page reading retain geometry', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByTestId('rail-projects').click()
  await expect(page.locator('#navigation-panel')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Collapse navigation panel' })).toBeFocused()
  await expect(page.locator('main')).toHaveAttribute('inert', '')
  await page.getByRole('separator').focus()
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => !document.querySelector('main')!.contains(document.activeElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Show page list' })).toBeFocused()
  await page.getByRole('button', { name: 'Keyboard shortcuts' }).click()
  await expect(page.getByRole('dialog')).toContainText('Alt+N')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts' })).toBeFocused()
  await page.getByRole('button', { name: 'Keyboard shortcuts' }).click()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts' })).toBeFocused()
  await newQuickNote(page)
  await addTextBox(page, 'Phone capture stays in the same canvas')
  await page.getByRole('button', { name: 'Insert table (3 × 3 with a header row)' }).click()
  const addRow = page.getByRole('button', { name: 'Add row below', exact: true })
  await expect(addRow).toBeVisible()
  await addRow.click()
  await expect(page.locator('.obj-text tr')).toHaveCount(4)
  await waitSaved(page)
  expect(await page.getByTestId('page-surface').evaluate((el) => (el as HTMLElement).style.width)).toBe('1200px')
  await page.getByRole('button', { name: 'Show page list' }).click()
  await page.getByRole('navigation', { name: 'Inbox', exact: true }).getByRole('button', { name: /Quick note/ }).last().click()
  await expect(page.locator('#navigation-panel')).toHaveCount(0)
  await expect(page.getByRole('main')).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 900, height: 700 })
  await page.getByRole('button', { name: 'Show page list' }).click()
  await expect(page.locator('#navigation-panel')).toBeVisible()
  expect((await page.locator('.main').boundingBox())!.width).toBeGreaterThanOrEqual(360)
  for (const width of [320, 768, 900]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.getByTestId('page-surface')).toBeVisible()
  }
})
